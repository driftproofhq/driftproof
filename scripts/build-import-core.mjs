// Canonical .mjs files are browser-safe. Node 22.0 uses generated CommonJS synchronously.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const source=path.join(root,'lib/import-core');
const check=process.argv.includes('--check');
const stale=[];
function write(file,text){const target=path.join(root,file);if(fs.existsSync(target)&&fs.readFileSync(target,'utf8')===text)return;if(check){stale.push(file);return;}fs.mkdirSync(path.dirname(target),{recursive:true});fs.writeFileSync(target,text);}
for(const name of fs.readdirSync(source).filter(n=>n.endsWith('.mjs')).sort()){
  const text=fs.readFileSync(path.join(source,name),'utf8');
  const banner='// Generated by scripts/build-import-core.mjs from lib/import-core/'+name+'. Do not edit.\n';
  const cjs=text.replace(/^import \{([^}]+)\} from '(\.\/[^']+)\.mjs';$/gm,(_,names,from)=>'const {'+names+'} = require(\''+from+'.cjs\');')
    .replace(/^export \{([^}]+)\};$/gm,(_,names)=>'module.exports = {'+names+'};');
  if(/^import |^export /m.test(cjs))throw Error(name+': unsupported module declaration');
  write('lib/import-core/'+name.replace(/\.mjs$/,'.cjs'),banner+cjs);
  write('docs/import-core/'+name,banner+text);
}
// Remove only this writer's old outputs when their location changes.
const previous=path.join(root,'docs/islands/import-core');
if(fs.existsSync(previous)){
  for(const name of fs.readdirSync(previous)){
    const file=path.join(previous,name);
    if(!fs.readFileSync(file,'utf8').startsWith('// Generated by scripts/build-import-core.mjs from lib/import-core/'))throw Error('unexpected file in old import module directory');
    if(check)stale.push('docs/islands/import-core/'+name);else fs.unlinkSync(file);
  }
  if(!check)fs.rmdirSync(previous);
}
if(stale.length){console.error('stale import modules: '+stale.join(', '));process.exitCode=1;}else console.log('import core: '+(check?'current':'built'));
